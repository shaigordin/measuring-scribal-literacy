def slugify(s):
    """ASCII key for a tradition or genre name: 'Ḫuwaššanna festivals' -> 'huwassannafestivals'."""
    s = unicodedata.normalize("NFKD", s.lower())
    return "".join(c for c in s if c.isascii() and c.isalnum())


def cth_ranges(cths):
    """[471, 472, 473, 404] -> '404, 471--473'"""
    cs = sorted(int(c) for c in cths)
    out, start = [], cs[0]
    for prev, cur in zip(cs, cs[1:] + [None]):
        if cur != prev + 1:
            out.append(str(start) if start == prev else f"{start}--{prev}")
            start = cur
    return ", ".join(out)


