    for sp in ("words", "signs"):
        evalrow(f"E4.{sp}", rep["E4_historical_no_logograms"][sp], f"{src} E4_historical_no_logograms.{sp}")
    rows = []
    for label, r, s in (("CTH 670 / 701 / 832 (abstract)", rep["E1_abstract_670_701_832"], "abstract"),
                        ("StBoT 73 groups + CTH-range controls", base["E1_historical"], "base"),
                        ("Literature-defined traditions (this paper)", rep["E1_historical"], "lit")):
        b = r["both"]
        rows.append(f"{label} & {b['classes']} & {num(b['n'])} & {pct(b['majority'])} & {pct(b['null_mean'])} & "
                    f"{pct(r['words']['acc'])} & {pct(r['signs']['acc'])} & \\textbf{{{pct(b['acc'])}}} \\\\")
