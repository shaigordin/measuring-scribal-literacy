"""Write every number and results table of the paper from the experiment outputs.

The paper never types a result by hand. Each number in the text is a macro \\Q{key} defined in
generated/numbers.tex, and each results table is a file generated/tab_*.tex. Both are written
here from the files that ../orphans/reproduce.sh produces, so rerunning the experiments and then
this script updates the paper. generated/numbers_index.csv lists every key with its value and the
file and field it was read from.

Usage: python3 make_numbers.py [--results ../orphans/results] [--out generated]
"""
