INDEX = []
LINES = []


def tex_escape(s):
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def pct(x, nd=0):
    if x is None:
        return "--"
    v = f"{100 * x:.{nd}f}"
    if float(v) == 0:
        v = v.lstrip("-")
    return v.replace("-", "\u2212") + "\\%"


def num(x):
    return f"{x:,}".replace(",", "{,}") if isinstance(x, int) else str(x)


def put(key, value, source):
    LINES.append(f"\\qtmdef{{{key}}}{{{value}}}")
    INDEX.append((key, value, source))


def load(run, name):
    with open(os.path.join(RES, run, name), encoding="utf-8") as f:
        return json.load(f) if name.endswith(".json") else list(csv.DictReader(f))


def table(name, lines):
    with open(os.path.join(OUT, f"tab_{name}.tex"), "w", encoding="utf-8") as f:
        f.write("% generated by make_numbers.py; do not edit\n" + "\n".join(lines) + "\n")


def evalrow(prefix, ev, source):
    """Accuracy, majority and permutation baselines of one loo_eval result."""
    for k in ("acc", "majority", "null_mean"):
        put(f"{prefix}.{k}", pct(ev[k]), f"{source}.{k}")
    put(f"{prefix}.p", ev["p"], f"{source}.p")
    put(f"{prefix}.n", num(ev["n"]), f"{source}.n")
    put(f"{prefix}.classes", ev["classes"], f"{source}.classes")


