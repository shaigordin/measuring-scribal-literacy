"""Transliteration of KBo 24.8 for Figure 1, with the lost signs at both ends of each line.

TLHdig 0.4 records where each line starts (<space c="..."/>, in characters of its layout) and
the signs of each line in Unicode (attribute cu, one character per sign, ▒ for a broken sign).
The number of lost signs is estimated relative to the line that reaches furthest on each side:
start offset in signs = (space - smallest space) / CHARS_PER_SIGN; a line ends at its start plus
its number of signs. Every broken edge shows at least one lost sign. The column continues on
both sides, so the counts are a lower bound, drawn as circles inside the brackets.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
XML = os.path.join(HERE, "..", "..", "orphans", "data", "TLHbasisONLINE25_1_ZENODO_Beta_04",
                   "CTH 470_XML_TLH", "KBo 24.8.xml")
OUT = os.path.join(HERE, "..", "generated", "kbo24_8_translit.tex")
CHARS_PER_SIGN = 3.3   # TLHdig layout: about 3.3 characters per sign in this text

# Preserved text as displayed (TLHdig 0.4). {L} and {R} mark where the lost signs go; text
# between [ and ] is restored by the editors.
LINES = {
    "1′": r"{L}x{R}",
    "2′": r"{L}\{MUNUS\}ŠU.G]I EGIR-\hit{pa} {R}",
    "3′": r"{L}x-\hit{kán} \{MUNUS\}ŠU.GI \hit{A-NA} EN SIS[KUR {R}",
    "4′": r"{L}x \hit{iš-na-a-aš pa-tal-ḫa-an} (erasure) \hit{an-da} {R}",
    "5′": r"{L}x-\hit{at-ši-kán ar-ḫa da-a-i} {R}",
    "6′": r"{L}x \{MUNUS\}ŠU.GI \{DUG\}\hit{ḫu-p}[\hit{u-} {R}",
    "7′": r"{L}\hit{ar-ḫ}]\hit{a wa-aḫ-nu-uz-zi} {R}",
    "8′": r"{L}x EN SISKUR \hit{ša-ra-a} {R}",
    "9′": r"{L}U]DU-\hit{ŠU ku-i-}\hb{⸢}\hit{e}\hb{⸣}\hit{-e}[\hit{š} {R}",
    "10′": r"{L}x x{R}",
}


def main():
    s = open(XML, encoding="utf-8").read()
    rows = []
    for m in re.finditer(r'<lb [^>]*lnr="([^"]+)"[^>]*cu="([^"]*)"/>(.*?)(?=<lb |\Z)', s, re.S):
        ln, cu, body = m.groups()
        sp = int(re.search(r'<space c="(\d+)"', body).group(1))
        rows.append((ln, sp, cu))
    cmin = min(sp for _, sp, _ in rows)
    start = {ln: (sp - cmin) / CHARS_PER_SIGN for ln, sp, _ in rows}
    end = {ln: start[ln] + len(cu) for ln, _, cu in rows}
    right = max(end.values())
    circ = "\\ensuremath{\\circ}"
    out = ["% generated by figures/make_fragment_translit.py; do not edit"]
    for ln, sp, cu in rows:
        text = LINES[ln]
        restored_start = not text.startswith("{L}x")   # the line opens with restored signs
        nl = round(start[ln]) if restored_start else max(round(start[ln]), 1)
        nr = max(round(right - end[ln]), 1)
        circles_l = "\\,".join([circ] * nl)
        if restored_start:
            left = "[" + (circles_l + "\\," if nl else "")
        else:
            left = "[" + circles_l + "]"
        tail = text.split("{R}")[0]
        open_bracket = tail.rfind("[") > tail.rfind("]")   # a restoration already runs to the edge
        right_txt = ("" if open_bracket else "[") + "\\,".join([circ] * nr) + "]"
        line = text.replace("{L}", left).replace("{R}", right_txt)
        out.append(f"{ln.replace('′', '$' + chr(39) + '$')} & {line} \\\\")
        print(ln, nl, nr)
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    half = 1 + (len(out) - 1) // 2   # two columns of lines for the figure
    for suffix, part in (("a", out[1:half]), ("b", out[half:])):
        open(OUT.replace(".tex", f"_{suffix}.tex"), "w", encoding="utf-8").write("\n".join([out[0]] + part) + "\n")


if __name__ == "__main__":
    main()
